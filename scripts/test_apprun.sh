#!/usr/bin/env bash
#
# Exercise the AppRun that make_appimage.sh generates, in a container.
#
# AppRun only runs on a user's machine at launch, so nothing else covers it.
# Two things there are easy to break and invisible until someone notices a
# generic icon in the dock:
#
#   * ``exec -a`` sets argv[0], which is where GTK takes g_get_prgname() from
#     and with it the Wayland app_id and the X11 WM_CLASS. The bundle stub
#     below is a real ELF on purpose: for a #! script the kernel discards
#     argv[0], so a shell stub could never show the difference.
#   * the desktop entry must be written once, follow a moved AppImage, and
#     stay out of the way when the user opts out.
#
# The AppRun under test is generated by the real block in make_appimage.sh,
# so the two cannot drift apart.
#
# Read-only against the local filesystem; only docker containers are created.
#
# Usage: scripts/test_apprun.sh [--image IMAGE]
#
set -euo pipefail

IMAGE="ubuntu:24.04"
while [ $# -gt 0 ]; do
  case "$1" in
    --image) IMAGE="$2"; shift 2 ;;
    -h|--help) sed -n '2,20p' "$0"; exit 0 ;;
    *) echo "error: unknown flag $1" >&2; exit 2 ;;
  esac
done

[ -f "pyproject.toml" ] || { echo "error: run from the project root" >&2; exit 1; }
command -v docker >/dev/null || { echo "error: docker not available" >&2; exit 1; }

WORK="$(mktemp -d)"
trap 'rm -rf "$WORK"' EXIT

APP_ID="$(grep -m1 '"identifier"' src-gui/src-tauri/tauri.conf.json |
          sed -E 's/.*"identifier"[[:space:]]*:[[:space:]]*"([^"]+)".*/\1/')"
[ -n "$APP_ID" ] || { echo "error: could not parse the Tauri identifier" >&2; exit 1; }

sed -n '/^# ── AppRun ─/,/^chmod 755 "$APPDIR\/AppRun"$/p' \
  scripts/make_appimage.sh > "$WORK/generate.sh"
APP_ID="$APP_ID" APPDIR="$WORK" bash "$WORK/generate.sh"
grep -q 'exec -a' "$WORK/AppRun" || {
  echo "error: the generated AppRun has no 'exec -a'; did the block move?" >&2; exit 1; }

{
  echo '#!/bin/bash'
  echo 'set -u'
  echo 'export DEBIAN_FRONTEND=noninteractive'
  echo 'apt-get update -qq >/dev/null 2>&1'
  echo 'apt-get install -y -qq desktop-file-utils gcc >/dev/null 2>&1'
  echo "APP_ID=\"$APP_ID\""
  cat <<'BODY'
set -u
pass=0; fail=0
check(){ local l="$1"; shift; if eval "$*" >/dev/null 2>&1; then echo "  PASS  $l"; pass=$((pass+1)); else echo "  FAIL  $l"; fail=$((fail+1)); fi; }

T=/tmp/appdir-test; rm -rf "$T"; mkdir -p "$T/home" "$T/AppDir/usr/lib/Perpetua" \
  "$T/AppDir/usr/share/icons/hicolor/256x256/apps"
cat > /tmp/stub.c <<'C'
#include <stdio.h>
int main(int argc, char **argv) { printf("argv0=%s\n", argv[0]); return 0; }
C
gcc -o "$T/AppDir/usr/lib/Perpetua/Perpetua" /tmp/stub.c || { echo "gcc failed"; exit 1; }
echo PNG > "$T/AppDir/usr/share/icons/hicolor/256x256/apps/perpetua.png"
cp /AppRun "$T/AppDir/AppRun"; chmod 755 "$T/AppDir/AppRun"
touch "$T/Perpetua.AppImage"

ENTRY="$T/home/applications/${APP_ID}.desktop"
ICON="$T/home/icons/hicolor/256x256/apps/${APP_ID}.png"
run(){ env XDG_DATA_HOME="$T/home" APPIMAGE="$T/Perpetua.AppImage" "$@"; }

echo "== 1. first launch integrates and sets argv[0] =="
out="$(run "$T/AppDir/AppRun" 2>&1)"
echo "  $out"
check "argv[0] is the app id"   "grep -q 'argv0=${APP_ID}' <<< \"\$out\""
check "desktop entry written"   "test -f '$ENTRY'"
check "icon installed"          "test -f '$ICON'"
check "Exec points at APPIMAGE" "grep -q 'Exec=\"$T/Perpetua.AppImage\"' '$ENTRY'"
check "Icon is an absolute path" "grep -q 'Icon=$ICON' '$ENTRY'"
check "StartupWMClass matches"  "grep -q 'StartupWMClass=${APP_ID}' '$ENTRY'"
check "entry is valid"          "! desktop-file-validate '$ENTRY' 2>&1 | grep -q error"

echo "== 2. second launch does not rewrite =="
before="$(stat -c %Y "$ENTRY")"; sleep 1
run "$T/AppDir/AppRun" >/dev/null 2>&1
check "entry untouched"         "test \"\$(stat -c %Y '$ENTRY')\" = '$before'"

echo "== 3. a moved AppImage is picked up =="
mv "$T/Perpetua.AppImage" "$T/Perpetua-moved.AppImage"
env XDG_DATA_HOME="$T/home" APPIMAGE="$T/Perpetua-moved.AppImage" "$T/AppDir/AppRun" >/dev/null 2>&1
check "Exec updated"            "grep -q 'Perpetua-moved.AppImage' '$ENTRY'"

echo "== 4. opt-outs =="
rm -f "$ENTRY"
env XDG_DATA_HOME="$T/home" APPIMAGE="$T/Perpetua-moved.AppImage" PERPETUA_NO_DESKTOP_INTEGRATION=1 \
  "$T/AppDir/AppRun" >/dev/null 2>&1
check "env var opts out"        "test ! -f '$ENTRY'"
out="$(env XDG_DATA_HOME="$T/home" APPIMAGE="$T/Perpetua-moved.AppImage" "$T/AppDir/AppRun" --no-desktop-integration 2>&1)"
check "flag opts out"           "test ! -f '$ENTRY'"
check "flag is not forwarded"   "! grep -q 'no-desktop-integration' <<< \"\$out\""

echo "== 5. extracted AppDir (no APPIMAGE) writes nothing =="
rm -f "$ENTRY"
env XDG_DATA_HOME="$T/home" "$T/AppDir/AppRun" >/dev/null 2>&1
check "nothing written"         "test ! -f '$ENTRY'"

echo "== 6. removal =="
env XDG_DATA_HOME="$T/home" APPIMAGE="$T/Perpetua-moved.AppImage" "$T/AppDir/AppRun" >/dev/null 2>&1
env XDG_DATA_HOME="$T/home" "$T/AppDir/AppRun" --remove-desktop-integration >/dev/null 2>&1
check "entry removed"           "test ! -f '$ENTRY'"
check "icon removed"            "test ! -f '$ICON'"

echo; echo "== $pass passed, $fail failed =="
exit $((fail>0))
BODY
} > "$WORK/inner.sh"

echo "Running the AppRun suite in $IMAGE (app id: $APP_ID)…"
docker run --rm \
  -v "$WORK/inner.sh:/inner.sh:ro" -v "$WORK/AppRun:/AppRun:ro" \
  "$IMAGE" bash /inner.sh
